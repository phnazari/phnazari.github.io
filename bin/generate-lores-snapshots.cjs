// Regenerate the fixed illustrations from the same simulation as the controls.
// Run from the repository root with: node bin/generate-lores-snapshots.cjs
// Optionally pass figure names to regenerate only those, e.g. feedback.
const fs = require("node:fs");
const vm = require("node:vm");
const source = fs.readFileSync("assets/js/lores.js", "utf8");
const post = fs.readFileSync("_posts/2026-10-16-lores.html", "utf8");
const requestedFigures = new Set(process.argv.slice(2));
const elements = new Map();
const element = (selector) => {
  if (!elements.has(selector)) {
    const id = selector.slice(1);
    const input = post.match(new RegExp(`<input[^>]*id="${id}"[^>]*>`));
    elements.set(selector, {
      value: input?.[0].match(/value="([^"]+)"/)?.[1] || "",
      innerHTML: "", dataset: {}, attributes: {},
      addEventListener() {},
      setAttribute(key, value) { this.attributes[key] = value; },
      getAttribute(key) { return this.attributes[key]; },
    });
  }
  return elements.get(selector);
};
const buttons = (key, values) => values.map((value, i) => {
  const button = element(`${key}-${value}`);
  button.dataset[key] = value;
  button.setAttribute("aria-pressed", String(i === 0));
  return button;
});
const groups = {
  "[data-lr-grouping]": buttons("lrGrouping", ["value", "key"]),
  "[data-lr-perturb]": buttons("lrPerturb", ["value", "key"]),
};
const context = vm.createContext({
  root: { clientWidth: 688 }, $: element, $$: (selector) => groups[selector] || [],
  exampleBits: 4,
  setPressed: (list, active) => list.forEach((button) => button.setAttribute("aria-pressed", String(button === active))),
  Math: Object.assign(Object.create(Math), { random: () => 0.75 }),
});
const simulation = source.slice(source.indexOf("  // SVG labels"), source.indexOf("  const batches"));
vm.runInContext(simulation + "\nglobalThis.snapshot = { drawDecay, groupingExample };", context);
const save = (name, svg) => {
  if (requestedFigures.size && !requestedFigures.has(name)) return;
  svg = svg.replaceAll(`lr-${name}-plot`, `lr-frozen-${name}-plot`);
  svg = svg.replace(/<rect[^>]*fill="transparent"[^>]*><title>[^<]*<\/title><\/rect>/g, "");
  fs.writeFileSync(`_includes/lores-frozen-${name}.liquid`, `{% comment %}Generated by bin/generate-lores-snapshots.cjs. Fixed synthetic example, not measured model data.{% endcomment %}\n${svg}\n`);
};
for (const name of ["rounding", "feedback"]) save(name, element(`#lr-${name}-chart`).innerHTML);

// Show several fixed decay rates on common axes.
const decay = element("#lr-decay-chart").innerHTML;
const rates = [0.9, 0.97, 0.995];
const decayDashes = ["2 5", "none", "9 5"];
const lines = rates.map((alpha, index) => {
  element("#lr-decay").value = alpha * 1000;
  context.snapshot.drawDecay();
  return element("#lr-decay-chart").innerHTML.match(/<polyline[^>]+\/>/)[0].replace("/>", ` stroke-dasharray="${decayDashes[index]}"/>`);
});
save("decay", decay.replace(/<polyline[^>]+\/>/, lines.join("\n")).replace(/<title[^>]*>.*?<\/title>/, '<title id="lr-decay-plot-title">Surviving error at three decay rates</title>').replace(/<desc[^>]*>.*?<\/desc>/, '<desc id="lr-decay-plot-desc">Fraction of a single injected error remaining after n updates, alpha to the power n. Decay factors are 0.9, 0.97, and 0.995. Stronger decay suppresses earlier errors faster.</desc>'));

// Show how the same large row sets the grid steps under each grouping.
const { matrix } = context.snapshot.groupingExample(4, 4, "value", "value");
const rowSteps = matrix.map(row => Math.max(...row.map(Math.abs)) / 7);
const columnSteps = matrix[0].map((_, j) => Math.max(...matrix.map(row => Math.abs(row[j]))) / 7);
const groupingPanel = (axis) => {
  const rows = axis === "value";
  const title = rows ? "Value grouping" : "Key grouping";
  const steps = rows ? rowSteps : columnSteps;
  const description = rows
    ? "Each row shares a grid. The large first row has step 0.43, while the other rows keep steps 0.11, 0.13, and 0.11."
    : "Each column shares a grid. The large first row sets all four column steps: 0.43, 0.19, 0.36, and 0.31. These grids apply to every row.";
  let svg = `<svg class="lr-grouping-diagram" viewBox="0 0 320 250" role="img" aria-labelledby="lr-grouping-${axis}-title lr-grouping-${axis}-desc"><title id="lr-grouping-${axis}-title">${title}: one scale per ${rows ? "row" : "column"}</title><desc id="lr-grouping-${axis}-desc">${description} Both panels show the same synthetic state, with first row 3.0, 1.3, 2.5, 2.2.</desc>`;
  svg += '<text x="124" y="18" class="lr-grouping-label">State S</text>';
  for (let group = 0; group < 4; group++) {
    const coarse = !rows || group === 0;
    const color = coarse ? "var(--lr-orange)" : "var(--lr-blue)";
    const x = rows ? 16 : 16 + group * 54;
    const y = rows ? 32 + group * 40 : 32;
    svg += `<rect x="${x}" y="${y}" width="${rows ? 212 : 50}" height="${rows ? 36 : 156}" rx="4" fill="${color}" fill-opacity="${coarse ? 0.19 : 0.06}" stroke="${color}" stroke-width="1.5"/>`;
    if (rows) {
      svg += `<path d="M234 ${y + 18}h17" stroke="${color}"/><text x="280" y="${y + 23}" style="fill:${color}">${steps[group].toFixed(2)}</text>`;
    } else {
      svg += `<path d="M${x + 25} 194v12" stroke="${color}"/><text x="${x + 25}" y="225" style="fill:${color}">${steps[group].toFixed(2)}</text>`;
    }
  }
  matrix.forEach((row, i) => row.forEach((value, j) => {
    svg += `<text x="${41 + j * 54}" y="${55 + i * 40}"${i === 0 ? ' class="lr-grouping-large"' : ""}>${value.toFixed(1).replace("-", "−")}</text>`;
  }));
  svg += `<text x="${rows ? 280 : 124}" y="${rows ? 18 : 248}" class="lr-grouping-label">Grid step</text></svg>`;
  return `<div class="lr-grouping-panel"><h4>${title}</h4><p class="lr-note">One scale per ${rows ? "value row" : "key column"}</p>${svg}<p class="lr-grouping-takeaway">${rows ? "Only the first row gets a coarse grid." : "Every row uses the coarser grids."}</p></div>`;
};
save("grouping", `<div class="lr-grouping-comparison">${groupingPanel("value")}${groupingPanel("key")}</div>`);
console.log(requestedFigures.size ? `Regenerated: ${[...requestedFigures].join(", ")}.` : "Generated four fixed illustrations from the interactive simulation.");
